def parse_faq(text):
    """The entries of `text` that have an answer, as [{"q": str, "a": [paragraph, ...]}]."""
    entries = []
    for block in text.split("\n---"):
        question, answer, current = [], [], None
        for line in block.strip().splitlines():
            stripped = line.strip()
            if stripped.startswith("q:"):
                current = question
                stripped = stripped[2:].strip()
            elif stripped.startswith("a:"):
                current = answer
                stripped = stripped[2:].strip()
            if current is not None:
                current.append(stripped)
        q = " ".join(s for s in question if s)
        paragraphs = [p.strip() for p in "\n".join(answer).split("\n\n") if p.strip()]
        if q and paragraphs:
            entries.append({"q": q, "a": [" ".join(p.split()) for p in paragraphs]})
    return entries


